def load_json_schema(filename: str, source_dir: Path = SOURCE_META_DIR) -> dict:
    """Load and parse one CALM JSON-Schema meta file."""
    path = source_dir / filename
    return json.loads(path.read_text(encoding="utf-8"))


def load_all_schemas(source_dir: Path = SOURCE_META_DIR) -> "OrderedDict[str, dict]":
    """Load every CALM meta JSON-Schema file in declared order."""
    out: "OrderedDict[str, dict]" = OrderedDict()
    for fname in SCHEMA_FILES:
        out[fname] = load_json_schema(fname, source_dir)
    return out


