#!/usr/bin/env python3
"""Convert the CALM JSON-Schema specification into a LinkML schema.

The Common Architecture Language Model (CALM) is distributed as a set of
JSON-Schema files under ``calm/release/<version>/meta/`` in this monorepo.
This script reads those JSON-Schema files and emits a single LinkML YAML
schema at ``linkml/src/calm/schema/calm.yaml`` augmented with enrichments
that JSON-Schema cannot express (ontology mappings, ``slot_uri`` wiring,
subset tags, folded descriptions, identifiers, ...).

Usage::

    cd linkml
    uv run python scripts/calm_to_linkml.py             # writes src/calm/schema/calm.yaml
    uv run python scripts/calm_to_linkml.py --check     # exits non-zero if drift
    uv run python scripts/calm_to_linkml.py --stdout    # write to stdout

Conversion rules at a glance:

* Each JSON-Schema ``defs/<name>`` becomes a LinkML ``class`` (PascalCase).
* Each scalar JSON property becomes a LinkML ``slot`` (snake_case),
  with hyphens in the source name preserved in ``aliases``.
* JSON ``enum`` arrays become LinkML ``enums`` (PascalCase).
* ``$ref`` to a sibling/foreign def is resolved into a ``range:`` reference.
* ``oneOf`` / ``anyOf`` at the property level become ``any_of`` on the slot,
  with an explicit list of alternative ranges (see SKILL note on
  ``gen-json-schema`` union expansion).
* ``required`` arrays mark slots as ``required: true``; ``pattern`` becomes
  a ``pattern:`` constraint; ``minItems: 1`` plus ``type: array`` becomes a
  ``required, multivalued`` combination on the host slot.
* Hand-curated overlays in ``ENRICHMENTS`` add ``description``,
  ``slot_uri``, ``class_uri``, ``*_mappings``, ``in_subset``, etc.
"""

