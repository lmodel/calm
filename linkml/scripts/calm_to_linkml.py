_FOLD_WIDTH = 78
_LITERAL_WRAP = 76


def _wrap_paragraphs(text: str, width: int) -> str:
    """Wrap each paragraph of ``text`` to ``width`` columns."""
    paragraphs = re.split(r"\n\s*\n", text)
    out: list[str] = []
    for para in paragraphs:
        collapsed = " ".join(para.split())
        if not collapsed:
            continue
        out.append(
            textwrap.fill(
                collapsed,
                width=width,
                break_long_words=False,
                break_on_hyphens=False,
            )
        )
    return "\n\n".join(out)


class _OrderedDumper(yaml.SafeDumper):
    """Emit dicts in insertion order with indented list items."""

    def increase_indent(self, flow: bool = False, indentless: bool = False) -> Any:  # type: ignore[override]
        return super().increase_indent(flow=flow, indentless=False)


def _ordered_dict_representer(dumper: yaml.SafeDumper, data: dict) -> yaml.MappingNode:
    return dumper.represent_mapping(
        yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG,
        list(data.items()),
    )


def _str_representer(dumper: yaml.SafeDumper, data: str) -> yaml.ScalarNode:
    if "\n" in data:
        wrapped = _wrap_paragraphs(data, _LITERAL_WRAP)
        return dumper.represent_scalar("tag:yaml.org,2002:str", wrapped, style="|")
    if len(data) > _FOLD_WIDTH and " " in data:
        return dumper.represent_scalar("tag:yaml.org,2002:str", data, style=">")
    return dumper.represent_scalar("tag:yaml.org,2002:str", data)


_OrderedDumper.add_representer(dict, _ordered_dict_representer)
_OrderedDumper.add_representer(OrderedDict, _ordered_dict_representer)
_OrderedDumper.add_representer(str, _str_representer)


def _dump_yaml(data: Any) -> str:
    return yaml.dump(
        data,
        Dumper=_OrderedDumper,
        default_flow_style=False,
        sort_keys=False,
        width=_FOLD_WIDTH,
        allow_unicode=True,
        indent=2,
    )


_ENTRY_RE = re.compile(r"^  [A-Za-z_][\w]*:")


def _add_entry_blanks(section_text: str) -> str:
    """Insert a single blank line before each second-level entry in a block."""
    lines = section_text.split("\n")
    out: list[str] = []
    seen_entry = False
    for line in lines:
        if _ENTRY_RE.match(line):
            if seen_entry:
                out.append("")
            seen_entry = True
        out.append(line)
    return "\n".join(out)


def _emit_section(key: str, value: Any, *, blank_between_entries: bool = False) -> str:
    if value is None:
        return ""
    if isinstance(value, (dict, list)) and len(value) == 0:
        return ""
    text = _dump_yaml({key: value}).rstrip() + "\n"
    if blank_between_entries:
        text = _add_entry_blanks(text)
    return text


def _emit_scalar(key: str, value: Any) -> str:
    if value is None:
        return ""
    return _dump_yaml({key: value}).rstrip() + "\n"


