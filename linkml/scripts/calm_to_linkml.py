def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(
        description=(__doc__ or "").splitlines()[0] if __doc__ else ""
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Do not write; exit non-zero if the on-disk schema differs.",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=SCHEMA_PATH,
        help=f"Output path (default: {SCHEMA_PATH})",
    )
    parser.add_argument(
        "--stdout",
        action="store_true",
        help="Write the schema to stdout instead of a file.",
    )
    args = parser.parse_args(argv)

    text = build_schema_text()

    if args.stdout:
        sys.stdout.write(text)
        return 0

    if args.check:
        if not args.out.exists():
            print(
                f"FAIL: {args.out} does not exist; run without --check to create it.",
                file=sys.stderr,
            )
            return 1
        if args.out.read_text(encoding="utf-8") != text:
            print(
                f"FAIL: {args.out} is out of date; rerun "
                f"``python {Path(__file__).name}``.",
                file=sys.stderr,
            )
            return 1
        print(f"OK: {args.out} matches the generator output.")
        return 0

    written = write_schema(args.out)
    print(f"Wrote {written} ({len(text):,} bytes)")
    return 0


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
