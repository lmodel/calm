def _collect_object_defs(
    schemas: "OrderedDict[str, dict]",
) -> list[tuple[str, str | None, dict]]:
    """Yield ``(filename, def_name | None, body)`` for every object def.

    The root of each schema file is yielded with ``def_name = None`` when it
    is itself a typed object (i.e. has ``properties``).
    """
    out: list[tuple[str, str | None, dict]] = []
    for fname, schema in schemas.items():
        if schema.get("type") == "object" and schema.get("properties"):
            out.append((fname, None, schema))
        for def_name, body in (schema.get("defs") or {}).items():
            if isinstance(body, dict) and (
                body.get("type") == "object" or body.get("properties")
            ):
                out.append((fname, def_name, body))
    return out


def slots_block(schemas: "OrderedDict[str, dict]") -> "OrderedDict[str, dict]":
    """Build the consolidated slot dict from every object's properties."""
    slots: "OrderedDict[str, dict]" = OrderedDict()
    seen: set[str] = set()
    for fname, def_name, body in _collect_object_defs(schemas):
        if (fname, def_name) not in DEFINITION_CLASSES:
            # Unmapped def — surface as a class via auto-derived name later;
            # skip slot collection for now (its properties are still walked).
            pass
        required_set = set(body.get("required") or [])
        for prop_name, prop in (body.get("properties") or {}).items():
            if prop_name == "additionalProperties":
                continue
            sname = slot_name_for(prop_name)
            if sname in seen:
                continue
            seen.add(sname)
            slots[sname] = convert_property(
                prop_name, prop, required=prop_name in required_set
            )

    # Always include identity / common slots even if no enrichment listed them.
    slots.setdefault(
        "unique_id",
        {"range": "string", "description": "Stable opaque identifier."},
    )

    # Apply enrichments (overlay on top of derived bodies).
    for sname, overlay in SLOT_ENRICHMENTS.items():
        body = slots.setdefault(sname, {"range": "string"})
        for k, v in overlay.items():
            if v is None:
                body.pop(k, None)  # None sentinel ->  delete the key
            else:
                body[k] = v

    return slots


