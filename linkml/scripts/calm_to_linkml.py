def slot_name_for(prop_name: str) -> str:
    """Convert a JSON property name (hyphenated) into a LinkML slot name."""
    return prop_name.replace("-", "_")


def convert_property(
    prop_name: str,
    prop: dict,
    *,
    required: bool,
) -> dict:
    """Convert one JSON-Schema property body into a LinkML slot body."""
    body: dict[str, Any] = {}

    desc = prop.get("description")
    if desc:
        body["description"] = desc

    # array ->  multivalued + element range
    if prop.get("type") == "array":
        items = prop.get("items") or {}
        if "$ref" in items:
            body["range"] = resolve_ref(items["$ref"])
        elif "anyOf" in items:
            body["any_of"] = _convert_choice_list(items["anyOf"])
            body["range"] = body["any_of"][0]["range"]
        elif items.get("type") == "object":
            body["range"] = "Metadata"
        else:
            body["range"] = json_scalar_to_linkml(items.get("type", "string"))
        body["multivalued"] = True
        if prop.get("minItems") and prop["minItems"] >= 1 and required:
            body["required"] = True
        elif required:
            body["required"] = True
        return body

    # $ref ->  reference to another class/type
    if "$ref" in prop:
        body["range"] = resolve_ref(prop["$ref"])
        if required:
            body["required"] = True
        return body

    # anyOf at property level ->  any_of
    if "anyOf" in prop:
        body["any_of"] = _convert_choice_list(prop["anyOf"])
        # The first alt becomes the nominal range so generators downstream
        # always have a concrete fallback type to emit.
        body["range"] = body["any_of"][0]["range"]
        if required:
            body["required"] = True
        return body

    # enum inline ->  emit as string with constrained values via pattern
    if "enum" in prop:
        body["range"] = "string"
        if required:
            body["required"] = True
        return body

    # const ->  equals_string
    if "const" in prop:
        body["range"] = "string"
        body["equals_string"] = prop["const"]
        if required:
            body["required"] = True
        return body

    json_type = prop.get("type", "string")
    if json_type == "object":
        body["range"] = "Metadata"
    else:
        body["range"] = json_scalar_to_linkml(json_type)

    if "pattern" in prop:
        body["pattern"] = prop["pattern"]
    if "format" in prop:
        body["annotations"] = {"json_format": prop["format"]}
    if "minimum" in prop:
        body["minimum_value"] = prop["minimum"]
    if "maximum" in prop:
        body["maximum_value"] = prop["maximum"]
    if "default" in prop:
        default = prop["default"]
        if isinstance(default, str):
            body["ifabsent"] = f"string({default})"
        elif isinstance(default, bool):
            body["ifabsent"] = f"boolean({str(default).lower()})"
        elif isinstance(default, int):
            body["ifabsent"] = f"int({default})"

    if required:
        body["required"] = True
    return body


def _convert_choice_list(alternatives: Iterable[dict]) -> list[dict]:
    """Turn a list of JSON-Schema alternatives into LinkML ``any_of`` form."""
    out: list[dict] = []
    for alt in alternatives:
        if "$ref" in alt:
            out.append({"range": resolve_ref(alt["$ref"])})
        elif alt.get("type") == "array":
            out.append({"range": "Metadata", "multivalued": True})
        elif alt.get("type") == "object":
            out.append({"range": "Metadata"})
        else:
            out.append({"range": json_scalar_to_linkml(alt.get("type", "string"))})
    return out


