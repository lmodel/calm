JSON_TO_LINKML_SCALAR: dict[str, str] = {
    "string": "string",
    "integer": "integer",
    "number": "float",
    "boolean": "boolean",
    "object": "Metadata",
}


def json_scalar_to_linkml(json_type: str) -> str:
    """Map a primitive JSON-Schema ``type`` keyword to a LinkML range."""
    return JSON_TO_LINKML_SCALAR.get(json_type, "string")


