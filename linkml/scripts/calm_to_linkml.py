def build_schema_text(
    schemas: "OrderedDict[str, dict] | None" = None,
) -> str:
    """Render the complete LinkML schema YAML text."""
    if schemas is None:
        schemas = load_all_schemas()

    slots = slots_block(schemas)
    # Inject synthetic slots not derived from JSON-Schema.
    for sname, sbody in SYNTHETIC_SLOTS.items():
        slots.setdefault(sname, sbody)

    classes = classes_block(schemas)
    enums = enums_block(schemas)

    blocks: list[list[str]] = [
        [GENERATED_HEADER, header_block()],
        [
            _emit_section("prefixes", prefixes_block()),
            _emit_scalar("default_prefix", DEFAULT_PREFIX),
            _emit_scalar("default_range", "string"),
        ],
        [_emit_section("imports", imports_block())],
        [_emit_section("subsets", subsets_block(), blank_between_entries=True)],
        [_emit_section("types", types_block(), blank_between_entries=True)],
        [_emit_section("enums", enums, blank_between_entries=True)],
        [_emit_section("slots", slots, blank_between_entries=True)],
        [_emit_section("classes", classes, blank_between_entries=True)],
    ]

    rendered: list[str] = []
    for sections in blocks:
        joined = "\n".join(s.rstrip() for s in sections if s.strip())
        if joined:  # pragma: no branch -- defensive; every block is populated
            rendered.append(joined)
    return "\n\n\n".join(rendered) + "\n"


def write_schema(target: Path | None = None) -> Path:
    target = target or SCHEMA_PATH
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(build_schema_text(), encoding="utf-8")
    return target


