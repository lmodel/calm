def _class_slots_for(body: dict) -> list[str]:
    """Return the list of LinkML slot names for an object body."""
    return [
        slot_name_for(p)
        for p in (body.get("properties") or {})
        if p != "additionalProperties"
    ]


def classes_block(schemas: "OrderedDict[str, dict]") -> "OrderedDict[str, dict]":
    """Build LinkML class dict from every mapped object def."""
    classes: "OrderedDict[str, dict]" = OrderedDict()

    for fname, def_name, body in _collect_object_defs(schemas):
        cname = DEFINITION_CLASSES.get((fname, def_name))
        if cname is None:
            continue
        slot_names = _class_slots_for(body)
        cls_body: dict[str, Any] = {}
        title = body.get("title")
        if title:
            cls_body["title"] = title
        desc = body.get("description")
        if desc:
            cls_body["description"] = desc
        if slot_names:
            cls_body["slots"] = slot_names
        classes[cname] = cls_body

    # Synthesise classes that aren't directly defs but are referenced.
    classes.setdefault(
        "OptionList",
        {
            "description": "Wrapper around the list of ``Decision`` alternatives in an options relationship.",
            "slots": ["decisions"],
        },
    )
    classes.setdefault(
        "RelationshipType",
        {
            "description": (
                "Tagged-union container for the variant body of a relationship. "
                "Exactly one of ``interacts``, ``connects``, ``deployed_in``, "
                "``composed_of``, ``options`` is populated; see "
                "``RelationshipKind`` for the discriminator values."
            ),
            "slots": [
                "interacts",
                "connects",
                "deployed_in",
                "composed_of",
                "options",
            ],
            "class_uri": "calm:RelationshipType",
            "in_subset": ["core"],
        },
    )

    # Apply enrichments
    for cname, overlay in CLASS_ENRICHMENTS.items():
        body = classes.setdefault(cname, {})
        for k, v in overlay.items():
            body[k] = v

    return classes


